package org.apache.geaflow.ai.retrieval.metadata;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.Charset;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/** Java 8 equivalents for the string-based file helpers added in Java 11. */
public final class Java8Files {

    private Java8Files() {
    }

    public static String readString(Path path) throws IOException {
        return readString(path, StandardCharsets.UTF_8);
    }

    public static String readString(Path path, Charset charset) throws IOException {
        return new String(Files.readAllBytes(path), charset);
    }

    public static Path writeString(Path path, CharSequence content, Charset charset) throws IOException {
        return Files.write(path, content.toString().getBytes(charset));
    }

    public static byte[] readAllBytes(InputStream input) throws IOException {
        byte[] buffer = new byte[8192];
        java.io.ByteArrayOutputStream output = new java.io.ByteArrayOutputStream();
        int count;
        while ((count = input.read(buffer)) != -1) {
            output.write(buffer, 0, count);
        }
        return output.toByteArray();
    }

}
